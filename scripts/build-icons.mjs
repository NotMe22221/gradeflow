function pathOf(file) {
  const svg = fs.readFileSync(path.join(dir, file), "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`no path in ${file}`);
  return paths.join(" ");
}

const missing = Object.entries(ICONS).filter(([, symbol]) => !fs.existsSync(path.join(dir, `${symbol}.svg`)));
if (missing.length) {
  console.error("Missing symbols:", missing.map(([n, s]) => `${n} -> ${s}`).join(", "));
  process.exit(1);
}

