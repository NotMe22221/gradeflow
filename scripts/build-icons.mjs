lines.push(``);
lines.push(`import { createIcon } from "./icon";`);
lines.push(``);
lines.push(`export { createIcon, type IconComponent, type IconProps } from "./icon";`);
lines.push(``);
for (const [name, symbol] of Object.entries(ICONS)) {
  const outline = pathOf(`${symbol}.svg`);
  const filled = fs.existsSync(path.join(dir, `${symbol}-fill.svg`)) ? pathOf(`${symbol}-fill.svg`) : outline;
  lines.push(`/** Material Symbol "${symbol}". */`);
  lines.push(`export const ${name} = /* @__PURE__ */ createIcon(${JSON.stringify(symbol)}, ${JSON.stringify(outline)}, ${JSON.stringify(filled)});`);
}
const out = path.join(process.cwd(), "src/components/icons/index.tsx");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n") + "\n");
